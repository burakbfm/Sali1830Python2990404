# GÖREV 04 | Uzay Gemisini Kurtar!

# Süre: 10 dakika
# Zorluk: Orta

# Proje Senaryosu
# Uzay gemisinin güvenli bölgeye ulaşabilmesi için üç başarılı uçuş yapması gerekmektedir.
# Ancak geminin yakıtı sınırlıdır.
# Oyuncu gerektiğinde yakıt doldurarak görevini tamamlamaya çalışacaktır.

# Öğrenciden Beklenenler
# Bir önceki göreve şu özellikleri ekle:
# -Yakıt doldurma seçeneği oluştur.
# -Yakıt doldurulduğunda 10 birim eklensin.
# -Yakıt kapasitesi 25'i geçmesin.
# -Başarılı uçuşları say.
# -Üç uçuş tamamlandığında oyun kazanılsın.